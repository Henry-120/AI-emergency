/**
 * 把文字轉成「緊急語氣」的朗讀版本。
 *
 * TTS 遇到全形句號、問號、驚嘆號會停頓明顯的一拍，逗號也會停半拍。
 * 一句地震警報唸下來，光是標點就多出一兩秒的空白——災害當下這段沉默
 * 會讓人以為程式當掉了，也拖慢後面自動開麥克風的時機。
 *
 * 這裡只改「唸出來的字串」，畫面上顯示的訊息仍保留正常標點，才好閱讀。
 */
export function toUrgentSpeech(text: string): string {
  return (
    text
      // 句中逗號直接移除，中文不靠它斷詞也聽得懂。
      .replace(/[，,]/g, "")
      // 句末標點換成頓號：仍保留極短的換氣，但不會停滿一拍。
      .replace(/[。！!？?；;：:]/g, "、")
      // 句點要避開小數點：「規模 6.5」被切開會念成「六、五」。
      .replace(/[．.](?!\d)/g, "、")
      // 連續頓號合併，避免「、、」被唸成兩次停頓。
      .replace(/、{2,}/g, "、")
      // 結尾不需要停頓，留著只會多等一拍。
      .replace(/[、\s]+$/g, "")
      .trim()
  );
}
